            <h2>Renewable energy and sustainability</h2>
            <div class="grid-2">
                <div>
                    <p class="lede">Our distillery and office have run on 100 per cent renewable energy since the solar array was installed in April 2025.</p>
                    <p>We use recyclable labels, glass bottles and cardboard boxes for all packaging, and run the business as efficiently as we can. As it grows we will keep a close eye on our carbon use and continue to operate as a carbon-neutral business in line with the UK's 2030 net-zero target. Our carbon reduction plan is available on request.</p>
                    <h3>Tree planting in Tanzania</h3>
                    <p>Environmental restoration is part of our corporate responsibility. The Wright Foundation organises tree-planting events in areas of Tanzania affected by deforestation, and we plan to purchase forestry carbon credits in the country. On 31 May 2025, Serengeti Spirits joined the Sintanizer Foundation and the Wright Foundation for a tree-planting day at Mianzini Primary School in Mabibo, Dar es Salaam.</p>
