                    <p class="stat">5%</p>
                    <p class="lede">Serengeti Spirits has pledged five per cent of its annual profits to the Wright Foundation, which works to tackle poverty in Tanzania.</p>
                    <p>Tanzania's economy is growing steadily, but it remains one of the poorest countries in the world. The Foundation has strong ties to local orphanages, supplying children's clothing, play equipment such as balls and skipping ropes, and books and other educational resources. Supporting children who have experienced significant loss is the part of the charity that matters most to us personally.</p>
                    <p>As a young foundation we provide monthly support to one children's home and are identifying the projects that will make the biggest difference to the next generation. We welcome outside support and collaboration.</p>
