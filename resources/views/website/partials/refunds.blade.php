            <h2 id="cancelling" class="band">If you cancel</h2>
            <p>Nearly all of our cancellation can be planned for. The table below shows how much of your total (excluding the cleaning fee) you get back, depending on when you tell us.</p>
            <table class="refund-table">
                <thead><tr><th>When you cancel</th><th>You get back</th></tr></thead>
                <tbody>
                    <tr><td>Over 8 weeks before arrival</td><td>Everything except your 25% deposit</td></tr>
                    <tr><td>8 weeks &ndash; 30 days before arrival</td><td>50% of the total (less any deposit already due)</td></tr>
                    <tr><td>29&ndash;8 days before arrival</td><td>25% of the total (less any deposit already due)</td></tr>
                    <tr><td>7 days or less before arrival</td><td>No refund</td></tr>
                    <tr><td>On or after arrival</td><td>No refund</td></tr>
                </tbody>
            </table>
            <p>Your deposit is non-refundable. Its purpose is to secure the dates, which is why it is not returned if you cancel.</p>

            <h2 id="we-cancel" class="band">If we cancel</h2>
            <p>It is very rare, but if we have to cancel your booking we will refund everything you have paid in full, promptly, and will not charge a cancellation fee. We are not responsible for any other costs you may have incurred as a result.</p>

            <h2 id="deposit" class="band">Deductions from your deposit</h2>
            <p>Your security deposit is returned within 7 days of departure, minus any deductions we have itemised for:</p>
            <ul>
                <li>Damage or breakages beyond normal wear and tear</li>
                <li>Excessive cleaning beyond the standard schedule</li>
                <li>Loss of property, fixture, fitting or contents</li>
                <li>Any extra services (for example, an additional night) used during your stay</li>
            </ul>
            <p>Where a deduction is needed, we will only take what is reasonable and will set out exactly what it is for, with evidence where possible, before anything is taken.</p>

            <h2 id="platform" class="band">Booking through a platform</h2>
            <p>If you booked through Airbnb, Booking.com or Vrbo, that platform&rsquo;s own cancellation policy and refund rules apply to your booking, and you should deal with them for any cancellation. The table above applies to direct bookings made with us.</p>

